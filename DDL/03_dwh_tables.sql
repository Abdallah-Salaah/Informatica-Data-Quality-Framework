-- 1. DIM_CUSTOMER
CREATE TABLE DIM_CUSTOMER (
    CUSTOMER_SK NUMBER GENERATED BY DEFAULT AS IDENTITY START WITH 1 INCREMENT BY 1 PRIMARY KEY,
    customer_id VARCHAR2(50),
    customer_unique_id VARCHAR2(50),
    customer_zip_code_prefix VARCHAR2(10),
    customer_city VARCHAR2(100),
    customer_state VARCHAR2(50),
    EFF_START_DATE DATE,
    EFF_END_DATE DATE,
    CURRENT_FLAG CHAR(1),
    INSERT_DATE TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    UPDATE_DATE TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    BATCH_ID NUMBER
);

-- 2. DIM_PRODUCT
CREATE TABLE DIM_PRODUCT (
    PRODUCT_SK NUMBER GENERATED BY DEFAULT AS IDENTITY START WITH 1 INCREMENT BY 1 PRIMARY KEY,
    product_id VARCHAR2(50),
    product_category_name VARCHAR2(100),
    product_weight_g NUMBER,
    INSERT_DATE TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    UPDATE_DATE TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    BATCH_ID NUMBER
);

-- 3. DIM_SELLER
CREATE TABLE DIM_SELLER (
    SELLER_SK NUMBER GENERATED BY DEFAULT AS IDENTITY START WITH 1 INCREMENT BY 1 PRIMARY KEY,
    seller_id VARCHAR2(50),
    seller_zip_code_prefix VARCHAR2(10),
    seller_city VARCHAR2(100),
    seller_state VARCHAR2(50),
    INSERT_DATE TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    UPDATE_DATE TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    BATCH_ID NUMBER
);

-- 4. DIM_DATE
CREATE TABLE DIM_DATE (
    DATE_SK NUMBER GENERATED BY DEFAULT AS IDENTITY START WITH 1 INCREMENT BY 1 PRIMARY KEY,
    date_actual DATE,
    day NUMBER,
    month NUMBER,
    quarter NUMBER,
    year NUMBER,
    weekday_name VARCHAR2(20),
    weekend_flag CHAR(1),
    INSERT_DATE TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    UPDATE_DATE TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    BATCH_ID NUMBER
);

-- 5. FACT_ORDER_ITEMS
CREATE TABLE FACT_ORDER_ITEMS (
    order_id VARCHAR2(50),
    order_item_number NUMBER,
    CUSTOMER_SK NUMBER REFERENCES DIM_CUSTOMER(CUSTOMER_SK),
    PRODUCT_SK NUMBER REFERENCES DIM_PRODUCT(PRODUCT_SK),
    SELLER_SK NUMBER REFERENCES DIM_SELLER(SELLER_SK),
    DATE_SK NUMBER REFERENCES DIM_DATE(DATE_SK),
    price NUMBER(10,2),
    freight_value NUMBER(10,2),
    order_status VARCHAR2(50),
    PRIMARY KEY (order_id, order_item_number)
);

-- 6. FACT_PAYMENTS
CREATE TABLE FACT_PAYMENTS (
    order_id VARCHAR2(50),
    payment_sequence NUMBER,
    CUSTOMER_SK NUMBER REFERENCES DIM_CUSTOMER(CUSTOMER_SK),
    DATE_SK NUMBER REFERENCES DIM_DATE(DATE_SK),
    payment_type VARCHAR2(50),
    payment_installments NUMBER,
    payment_value NUMBER(10,2),
    PRIMARY KEY (order_id, payment_sequence)
);

