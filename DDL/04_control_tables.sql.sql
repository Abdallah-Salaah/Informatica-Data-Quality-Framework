-- 1. ETL_BATCH_LOG
CREATE TABLE ETL_BATCH_LOG (
    BATCH_ID NUMBER GENERATED ALWAYS AS IDENTITY START WITH 1 INCREMENT BY 1 PRIMARY KEY,
    WORKFLOW_NAME VARCHAR2(100),
    START_TIME TIMESTAMP,
    END_TIME TIMESTAMP,
    ROWS_READ NUMBER,
    ROWS_LOADED NUMBER,
    ROWS_REJECTED NUMBER,
    STATUS VARCHAR2(20) -- RUNNING, SUCCESS, FAILED
);

-- 2. ETL_ERROR_LOG
CREATE TABLE ETL_ERROR_LOG (
    ERROR_ID NUMBER GENERATED ALWAYS AS IDENTITY START WITH 1 INCREMENT BY 1 PRIMARY KEY,
    BATCH_ID NUMBER,
    MAPPING_NAME VARCHAR2(100),
    SOURCE_KEY VARCHAR2(100),
    ERROR_REASON VARCHAR2(4000),
    ERROR_DATE TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- 3. ETL_RECON_LOG
CREATE TABLE ETL_RECON_LOG (
    BATCH_ID NUMBER,
    TABLE_NAME VARCHAR2(100),
    SOURCE_COUNT NUMBER,
    TARGET_COUNT NUMBER,
    SOURCE_SUM NUMBER(15,2),
    TARGET_SUM NUMBER(15,2),
    STATUS VARCHAR2(20), -- BALANCED, MISMATCH
    PRIMARY KEY (BATCH_ID, TABLE_NAME)
);
